ANGLE ANGLE::GetInversed()
{
    return ANGLE(static_cast<uint8_t>(static_cast<unsigned int>(value)+0x80u));
}

void ANGLE::Inverse()
{
    value=static_cast<uint8_t>(static_cast<unsigned int>(value)+0x80u);
}

ANGLE ANGLE::Difference(const ANGLE* other)
{
    const uint8_t d1=static_cast<uint8_t>(static_cast<unsigned int>(value)-other->value);
    const uint8_t d2=static_cast<uint8_t>(static_cast<unsigned int>(other->value)-value);
    return ANGLE(static_cast<uint8_t>(d1<d2 ? d1 : d2));
}

// Retail rebuilds the two Y-projection tables from the base Sin/Cos tables on
// every call, multiplying each entry by the constant at 0x004B51A8.
void ANGLE::Init()
{
    for (int i=0;i<256;++i) {
        kRetailSinYTable[i]=FSin[i]*kRetailYScale;
        kRetailCosYTable[i]=kRetailCosTable[i]*kRetailYScale;
    }
}

// Retail serializes ANGLE as a DWORD.  Read into a 32-bit temporary and keep
// only its low byte; this is deliberately asymmetric with the one-byte runtime
// storage but symmetric with ANGLE::Write(STREAM*).
void ANGLE::Read(STREAM* res)
{
    int direction;
    res->Read(&direction,4u);
    value=static_cast<uint8_t>(direction);
}
