float ANGLE::Sin()
{
    return FSin[value];
}

float ANGLE::Cos()
{
    return kRetailCosTable[value];
}

// Retail .data starts with a byte-identical copy of the normal table; ANGLE::Init scales this Y table in place.
float ANGLE::SinY()
{
    return kRetailSinYTable[value];
}

float ANGLE::CosY()
{
    return kRetailCosYTable[value];
}


float ANGLE::RotateX(float x,float y)
{
    return x * Cos() - y * Sin();
}

float ANGLE::RotateY(float x,float y)
{
    return x * Sin() + y * Cos();
}

